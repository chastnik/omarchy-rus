#!/usr/bin/env bash
# title: Переход на встроенный перевод Omarchy 4.5 (уборка за omarchy-rus 1.x)
# group: base
# default: on
# desc: убирает то, что теперь переводит сам Omarchy: расширение меню, свои меню Super+K, конфиг fastfetch, клоны плагинов 1.x, старый хук; на чистой системе ничего не делает
set -euo pipefail
CFG="$HOME/.config/omarchy"
D="$HOME/.local/share/omarchy-rus"

if [ ! -d /usr/share/omarchy/default/i18n/ru ] || ! command -v omarchy-language >/dev/null; then
  echo "Omarchy без встроенной локализации (нужна 4.5+): сначала выполните «omarchy update»." >&2
  echo "Для старых версий Omarchy используйте omarchy-rus 1.5.0." >&2
  exit 1
fi

# omarchy plugin remove перезагружает шелл, и следующая команда сразу после этого получает
# «omarchy-shell is not responding»: ждём ответа шелла и повторяем.
wait_shell() {
  local _
  for _ in $(seq 20); do omarchy-shell shell ping >/dev/null 2>&1 && return 0; sleep 1; done
  return 1
}
remove_clone() {
  local _
  for _ in 1 2 3; do
    [ -d "$CFG/plugins/$1" ] || return 0
    wait_shell || true
    omarchy plugin remove "$1" --yes >/dev/null 2>&1 || true
  done
  [ ! -d "$CFG/plugins/$1" ]
}

MENU="$CFG/extensions/omarchy-menu.jsonc"
if grep -qF "Generated by omarchy-rus/translate-menu.py" "$MENU" 2>/dev/null; then
  rm -f "$MENU" && echo "Удалено расширение меню $MENU"
fi

BINDINGS="$HOME/.config/hypr/bindings.lua"
if grep -qF -- "-- >>> omarchy-rus: keybindings" "$BINDINGS" 2>/dev/null; then
  cp "$BINDINGS" "$BINDINGS.bak.$(date +%s)"
  sed -i '/^-- >>> omarchy-rus: keybindings$/,/^-- <<< omarchy-rus: keybindings$/d' "$BINDINGS"
  echo "Super+K, Super+Alt+K, Super+Ctrl+K снова открывают стоковые меню"
  hyprctl reload >/dev/null 2>&1 || true
fi
rm -f "$HOME"/.local/bin/omarchy-menu{,-tmux,-herdr}-keybindings-ru

# Русский fastfetch: About (omarchy-launch-about) с 4.5 переводит заголовки сам, а свой конфиг это отключает.
FF="$HOME/.config/fastfetch/config.jsonc"
if grep -qF "// omarchy-rus: generated from" "$FF" 2>/dev/null; then
  rm -f "$FF" && echo "Удалён $FF: About переводит Omarchy"
fi

# Старый хук post-update пересобирал бы меню и Super+K после каждого «omarchy update»: заменяем на новый.
HOOK="$CFG/hooks/post-update.d/omarchy-rus.hook"
if grep -qE "translate-menu|keybindings-ru|check-i18n" "$HOOK" 2>/dev/null; then
  bash "$RUS_DIR/modules/90-post-update-hook.sh" && echo "Хук post-update обновлён"
fi

# Клоны omarchy-rus 1.x: код Omarchy до 4.5 с зашитыми переводами. Чужие клоны не трогаем.
# omarchy plugin remove возвращает оригинал на место клона в баре (резервная копия клона остаётся в plugins/).
# network, weather и emojis 1.x тоже убираем: модули dns, weather и emojis создадут их заново
# (клоны 2.x перечислены в списке v2 файла clones.json).
v2=$(jq -r '(.v2 // [])[]' "$D/clones.json" 2>/dev/null || true)
failed=0
for name in clock bluetooth audio power monitor speedtest disk-speedtest tailscale notifications reminders \
            clipboard image-picker wifiqr dropbox agents indicators microphone tray system-update \
            network weather emojis; do
  [ -d "$CFG/plugins/$USER.$name" ] || continue
  grep -qx "$name" <<< "$v2" && continue
  if remove_clone "$USER.$name"; then
    echo "Клон $USER.$name убран, на месте оригинал omarchy.$name"
  else
    echo "Не удалось убрать клон: omarchy plugin remove $USER.$name --yes" >&2
    failed=1
  fi
done
exit $failed
